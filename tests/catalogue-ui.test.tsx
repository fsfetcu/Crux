// @vitest-environment jsdom
import { afterEach,beforeEach,describe,expect,it,vi } from "vitest";
import { cleanup,render,screen,within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import App from "../src/App";
import { PROFILE_KEY } from "../src/profiles";
import type { ProfileData } from "../src/profiles";
const saved=()=>JSON.parse(localStorage.getItem(PROFILE_KEY)!) as ProfileData;
beforeEach(()=>{localStorage.clear();window.scrollTo=vi.fn();});
afterEach(()=>{cleanup();vi.restoreAllMocks();});
describe("catalogue and training log flows",()=>{
  it("creates a weighted exercise, adds it to a plan, overrides the day, logs grades/weights, and reopens its statistics",async()=>{
    const user=userEvent.setup();let view=render(<App/>);
    await user.click(screen.getByRole("button",{name:"Catalogue"}));
    await user.click(screen.getByRole("button",{name:"New exercise"}));
    let dialog=screen.getByRole("dialog");
    await user.type(within(dialog).getByLabelText("Session name"),"Weighted row");
    await user.type(within(dialog).getByLabelText("Weighted row kilograms"),"22.5");
    await user.click(within(dialog).getByRole("button",{name:"Save to catalogue"}));
    expect(saved().catalogue!.find((i)=>i.name==="Weighted row")!.exercises[0].weightKg).toBe(22.5);
    expect(saved().profiles[0].state.templates.some((t)=>t.name==="Weighted row")).toBe(false);
    const card=screen.getByRole("heading",{name:"Weighted row"}).closest("article")!;
    await user.click(within(card).getByRole("button",{name:"Add to training plan"}));
    dialog=screen.getByRole("dialog");
    await user.selectOptions(within(dialog).getByLabelText("Workout type in this plan"),"strength");
    await user.click(within(dialog).getByRole("button",{name:"Add to plan"}));
    await user.click(screen.getByRole("button",{name:"Training plan"}));
    await user.click(screen.getByRole("tab",{name:"Strength"}));
    await user.click(screen.getByRole("button",{name:"Drag Weighted row from Weighted row into calendar"}));
    dialog=screen.getByRole("dialog");
    const dayWeight=within(dialog).getByLabelText("Weighted row kilograms for this day");
    await user.clear(dayWeight);await user.type(dayWeight,"25");
    await user.click(within(dialog).getByRole("button",{name:"Add to planner"}));
    await user.click(screen.getByRole("button",{name:"Complete Weighted row"}));
    dialog=screen.getByRole("dialog");
    const actualWeight=within(dialog).getByLabelText("Weighted row kilograms");
    await user.clear(actualWeight);await user.type(actualWeight,"27.5");
    await user.click(within(dialog).getByRole("button",{name:"Add grade count"}));
    await user.type(within(dialog).getByLabelText("Grade 1",{exact:true}),"6a");
    await user.clear(within(dialog).getByLabelText("Grade 1 count"));await user.type(within(dialog).getByLabelText("Grade 1 count"),"5");
    await user.click(within(dialog).getByRole("button",{name:"Save workout"}));
    expect(saved().profiles[0].state.logs[0]).toMatchObject({gradeCounts:[{system:"font",grade:"6A",count:5}],exercises:[{weightKg:27.5}]});
    expect(saved().profiles[0].state.templates.find((t)=>t.name==="Weighted row")!.exercises[0].weightKg).toBe(22.5);
    view.unmount();view=render(<App/>);
    await user.click(screen.getByRole("button",{name:"Training history"}));
    expect(screen.getByRole("heading",{name:"Grades you’ve climbed"})).toBeTruthy();
    const table=screen.getByRole("table");expect(within(table).getByRole("rowheader",{name:"6A"})).toBeTruthy();
    expect(within(table).getByText("5",{exact:true})).toBeTruthy();
    expect(saved().catalogue!.find((i)=>i.name==="Weighted row")!.exercises[0].weightKg).toBe(22.5);
  });
  it("filters the catalogue and adds an endurance workout to a new type without changing other goals",async()=>{
    const user=userEvent.setup();render(<App/>);
    await user.click(screen.getByRole("button",{name:"Catalogue"}));
    await user.selectOptions(screen.getByLabelText("Catalogue focus"),"Endurance");
    expect(screen.queryByRole("heading",{name:"Board max power"})).toBeNull();
    const card=screen.getByRole("heading",{name:"20-boulder endurance"}).closest("article")!;
    await user.click(within(card).getByRole("button",{name:"Add to training plan"}));
    const dialog=screen.getByRole("dialog");
    await user.selectOptions(within(dialog).getByLabelText("Workout type in this plan"),"new");
    await user.click(within(dialog).getByRole("button",{name:"Add to plan"}));
    const data=saved(),template=data.profiles[0].state.templates.find((t)=>t.name==="20-boulder endurance")!;
    expect(template.targetRpe).toBe(5);expect(data.profiles[0].state.settings.goals.hard).toBe(2);
    expect(data.profiles[0].state.settings.goals[template.category]).toBe(1);
  });
});
